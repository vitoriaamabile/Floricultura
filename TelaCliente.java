    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // Atualizar as informações do objeto meuCliente
        meuCliente.setNome(txtNome.getText());
        meuCliente.setTelefone(txtTelefone.getText());
        meuCliente.setCpf(txtCPF.getText());
        
        // Instanciar um objeto DAO
        ClienteDAO dao = new ClienteDAO();
        
        // Invocar o método update
        dao.update(meuCliente);
        
        // Limpar o form e atualizar a tabela
        limpar();
        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

